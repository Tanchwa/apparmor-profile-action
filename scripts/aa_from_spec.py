#!/usr/bin/env python3
"""Render a declarative YAML/JSON spec into an AppArmor profile.

Used when a repo cannot exercise its workload in CI: instead of learning from
audit records, the author states what the application is allowed to touch and
this renders the equivalent profile.  See examples/apparmor.spec.yaml.
"""

import argparse
import json
import sys

try:
    import yaml
except ImportError:  # pragma: no cover - runner installs it
    yaml = None

PERM_ORDER = "mrwalkix"
# Allow rules imply read, because a process that writes a file almost always
# opens it readable first. Deny rules must not: "deny write" that also denied
# reads would silently revoke access the author never asked to revoke.
FILE_SECTIONS = [
    ("read", "r"),
    ("write", "rw"),
    ("append", "ra"),
    ("create", "rw"),
    ("lock", "k"),
    ("link", "l"),
    ("mmap", "rm"),
]
DENY_SECTIONS = [
    ("read", "r"),
    ("write", "w"),
    ("append", "a"),
    ("create", "w"),
    ("lock", "k"),
    ("link", "l"),
    ("mmap", "m"),
    ("exec", "x"),
]


def die(msg):
    sys.stderr.write("error: %s\n" % msg)
    sys.exit(1)


def load(path):
    with open(path) as fh:
        text = fh.read()
    if path.endswith(".json"):
        return json.loads(text)
    if yaml is None:
        die("PyYAML is not installed and the spec is not JSON (pip install pyyaml)")
    return yaml.safe_load(text)


def quote(path):
    return '"%s"' % str(path).replace('"', '\\"')


def as_list(value, field):
    if value is None:
        return []
    if isinstance(value, (str, int)):
        return [value]
    if isinstance(value, list):
        return value
    die("%s must be a string or a list, got %s" % (field, type(value).__name__))


def norm_perms(perms):
    return "".join(c for c in PERM_ORDER if c in set(perms))


def render(spec, overrides):
    name = overrides.get("name") or spec.get("name")
    if not name:
        die("spec needs a 'name'")

    mode = overrides.get("mode") or spec.get("mode", "enforce")
    if mode not in ("enforce", "complain"):
        die("mode must be 'enforce' or 'complain', got %r" % mode)

    attach = overrides.get("attach") or spec.get("attach", "")
    flags = as_list(spec.get("flags", ["attach_disconnected", "mediate_deleted"]), "flags")
    if mode == "complain" and "complain" not in flags:
        flags = list(flags) + ["complain"]

    L = []
    L.append("# AppArmor profile for %s" % name)
    L.append("# Generated by apparmor-profile-action from a declarative spec.")
    L.append("# Edit the spec, not this file -- re-running the action overwrites it.")
    L.append("")
    if spec.get("abi"):
        L.append("abi <abi/%s>," % spec["abi"])
    L.append("include <tunables/global>")
    L.append("")

    header = "profile %s" % name
    if attach:
        header += " %s" % attach
    if flags:
        header += " flags=(%s)" % ",".join(flags)
    L.append(header + " {")

    abstractions = as_list(spec.get("abstractions", ["base"]), "abstractions")
    for item in abstractions:
        L.append("  include <abstractions/%s>" % item)
    if abstractions:
        L.append("")

    caps = as_list(spec.get("capabilities"), "capabilities")
    if caps:
        L.append("  # capabilities")
        for cap in sorted(caps):
            L.append("  capability %s," % cap)
        L.append("")

    network = spec.get("network")
    if network is True:
        L.append("  # network")
        L.append("  network,")
        L.append("")
    elif network:
        L.append("  # network")
        for entry in as_list(network, "network"):
            if isinstance(entry, dict):
                parts = [entry[k] for k in ("family", "type", "protocol") if entry.get(k)]
                L.append("  network %s," % " ".join(str(p) for p in parts))
            else:
                L.append("  network %s," % entry)
        L.append("")

    files = spec.get("files") or {}
    if not isinstance(files, dict):
        die("'files' must be a mapping of permission -> paths")

    rules = {}
    for section, perms in FILE_SECTIONS:
        for path in as_list(files.get(section), "files.%s" % section):
            rules.setdefault(str(path), set()).update(perms)
    for path, perms in (files.get("raw") or {}).items():
        rules.setdefault(str(path), set()).update(perms)

    if rules:
        L.append("  # files")
        for path in sorted(rules):
            L.append("  %s %s," % (quote(path), norm_perms(rules[path])))
        L.append("")

    execs = files.get("exec") or spec.get("exec") or []
    if execs:
        L.append("  # executables")
        for entry in as_list(execs, "exec"):
            if isinstance(entry, dict):
                path = entry.get("path") or die("exec entries need a 'path'")
                xmode = entry.get("mode", "ix")
            else:
                path, xmode = str(entry), "ix"
            L.append("  %s r%s," % (quote(path), xmode))
        L.append("")

    for key, keyword in (("signal", "signal"), ("ptrace", "ptrace"),
                         ("unix", "unix"), ("mount", "mount"), ("dbus", "dbus")):
        entries = as_list(spec.get(key), key)
        if not entries:
            continue
        L.append("  # %s" % key)
        for entry in entries:
            entry = str(entry).strip().rstrip(",")
            L.append("  %s," % entry if entry.startswith(keyword) else "  %s %s," % (keyword, entry))
        L.append("")

    deny = spec.get("deny") or {}
    deny_lines = []
    if isinstance(deny, dict):
        for section, perms in DENY_SECTIONS:
            for path in as_list(deny.get(section), "deny.%s" % section):
                deny_lines.append("  deny %s %s," % (quote(path), norm_perms(perms)))
        for path, perms in (deny.get("raw") or {}).items():
            deny_lines.append("  deny %s %s," % (quote(path), norm_perms(perms)))
    else:
        for entry in as_list(deny, "deny"):
            deny_lines.append("  deny %s," % str(entry).strip().rstrip(","))
    if deny_lines:
        L.append("  # denials (these win over any allow rule above)")
        L.extend(sorted(deny_lines))
        L.append("")

    children = spec.get("children") or {}
    for child, body in children.items():
        L.append("  profile %s {" % child)
        for line in str(body).strip().splitlines():
            L.append("    %s" % line.strip())
        L.append("  }")
        L.append("")

    raw = spec.get("raw")
    if raw:
        L.append("  # verbatim rules from the spec")
        for line in str(raw).strip().splitlines():
            L.append("  %s" % line.strip())
        L.append("")

    while L and L[-1] == "":
        L.pop()
    L.append("}")
    L.append("")
    return "\n".join(L)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("spec", help="path to the YAML or JSON spec")
    p.add_argument("--name", default="", help="override the profile name")
    p.add_argument("--attach", default="", help="override the attachment path")
    p.add_argument("--mode", default="", choices=["", "enforce", "complain"])
    p.add_argument("-o", "--output", default="-")
    args = p.parse_args()

    spec = load(args.spec)
    if not isinstance(spec, dict):
        die("spec must be a mapping at the top level")

    overrides = {k: v for k, v in vars(args).items() if k in ("name", "attach", "mode") and v}
    text = render(spec, overrides)

    if args.output == "-":
        sys.stdout.write(text)
    else:
        with open(args.output, "w") as fh:
            fh.write(text)
        sys.stderr.write("wrote %s\n" % args.output)


if __name__ == "__main__":
    main()
